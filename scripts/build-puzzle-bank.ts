// Builds src/engine/puzzleBank.generated.ts: per difficulty, puzzles the generator graded at
// exactly that level. Deterministic (seeds 1, 2, 3, ...), so rerunning it gives the same file.
// Run with: npm run build:bank
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DIFFICULTIES, type Difficulty } from "../src/engine/grader";
import { generatePuzzle } from "../src/engine/generator";
import { formatGrid } from "../src/engine/grid";

const PUZZLES_PER_DIFFICULTY = 20;
/** Stop looking for a level after this many seeds, so a broken generator cannot loop forever. */
const MAX_SEEDS_PER_DIFFICULTY = 20_000;
const OUTPUT_FILE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/engine/puzzleBank.generated.ts");

function collect(difficulty: Difficulty): string[] {
  const puzzles = new Set<string>();
  const startedAt = Date.now();
  for (let seed = 1; puzzles.size < PUZZLES_PER_DIFFICULTY; seed++) {
    if (seed > MAX_SEEDS_PER_DIFFICULTY) throw new Error(`Only ${puzzles.size} ${difficulty} puzzles after ${MAX_SEEDS_PER_DIFFICULTY} seeds`);
    // One full grid per seed: a miss is cheaper to skip than to retry within the seed.
    const generated = generatePuzzle({ difficulty, seed, maxAttempts: 1 });
    if (generated.difficulty === difficulty) puzzles.add(formatGrid(generated.puzzle));
    if (seed % 100 === 0) console.log(`  ${difficulty}: ${puzzles.size}/${PUZZLES_PER_DIFFICULTY} after ${seed} seeds`);
  }
  console.log(`${difficulty}: ${puzzles.size} puzzles in ${((Date.now() - startedAt) / 1000).toFixed(1)}s`);
  return [...puzzles];
}

const bank = Object.fromEntries(DIFFICULTIES.map((difficulty) => [difficulty, collect(difficulty)]));
const body = DIFFICULTIES.map(
  (difficulty) => `  [Difficulty.${difficulty[0].toUpperCase()}${difficulty.slice(1)}]: [\n${bank[difficulty].map((puzzle) => `    "${puzzle}",`).join("\n")}\n  ],`,
).join("\n");

writeFileSync(
  OUTPUT_FILE,
  `// Generated by scripts/build-puzzle-bank.ts (npm run build:bank). Do not edit by hand.
import { Difficulty } from "./grader";

export const PUZZLE_BANK: Readonly<Record<Difficulty, readonly string[]>> = {
${body}
};
`,
);
console.log(`Wrote ${path.relative(process.cwd(), OUTPUT_FILE)}`);
